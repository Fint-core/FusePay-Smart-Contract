//! # fusepay-access-control
//!
//! Role-based access control contract for the FusePay platform.
//!
//! ## Roles
//!
//! | Role      | Description |
//! |-----------|-------------|
//! | Owner     | Superuser — transfers ownership, manages admins |
//! | Admin     | Configures contract parameters, manages operators |
//! | Operator  | Day-to-day operations (fee collection, releases) |
//! | Treasury  | Authorises treasury withdrawals below threshold |
//! | Auditor   | Read-only — cannot modify state |
//!
//! ## Role Hierarchy
//!
//! `Owner > Admin > Operator / Treasury > Auditor`
//!
//! A caller with a higher role always satisfies a check for a lower role.
//!
//! ## Usage
//!
//! Other contracts call `AccessControlContract::has_role` via cross-contract
//! invocation to validate permissions before executing privileged operations.

